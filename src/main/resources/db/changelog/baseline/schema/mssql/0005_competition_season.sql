CREATE TABLE competition_season (
    id                          BIGINT IDENTITY(1,1)    PRIMARY KEY,
    competition_id              VARCHAR(40)  NOT NULL REFERENCES competition(id),
    season_id                   VARCHAR(10)  NOT NULL REFERENCES season(id),
    season_start                DATE         NOT NULL,
    season_end                  DATE         NOT NULL,
    first_round_date            DATE,
    start_second_leg            DATE         NOT NULL,
    max_matches_per_day         INT          NOT NULL CHECK (max_matches_per_day > 0),
    max_days_advance_match      INT          NOT NULL CHECK (max_days_advance_match >= 0),
    max_days_postpone_match     INT          NOT NULL CHECK (max_days_postpone_match >= 0),
    allow_maj                   BIT      NOT NULL DEFAULT 1,
    rounds_forward_look         INT          NOT NULL DEFAULT 3,
    time_assigns_forward_look   INT          NOT NULL DEFAULT 20,
    last_round_to_assign        INT          NOT NULL DEFAULT 5,
    matchday_pattern            VARCHAR(12)  NOT NULL DEFAULT 'sat-sun' CHECK (matchday_pattern IN ('sat','sat-sun','fri-sat-sun')),
    ramadan_start               DATE,
    ramadan_end                 DATE,
    ramadan_slot                VARCHAR(5),
    no_light_slot               VARCHAR(5),
    groups_to_run               INT          NOT NULL DEFAULT 1,
    group_to_optimize_times     INT          NOT NULL DEFAULT 1,
    groups_can_go_to_maj        VARCHAR(40)  NOT NULL DEFAULT '1',
    round_calculation_order     VARCHAR(400) NOT NULL,
    depends_on_competition_id   VARCHAR(40)  REFERENCES competition(id),
    include_dependency          BIT      NOT NULL DEFAULT 0,
    row_version                 INT          NOT NULL DEFAULT 0,
    updated_at                  DATETIMEOFFSET  NOT NULL DEFAULT SYSDATETIMEOFFSET(),
    CONSTRAINT uq_competition_season UNIQUE (competition_id, season_id),
    CONSTRAINT ck_season_dates CHECK (season_end >= season_start)
);
